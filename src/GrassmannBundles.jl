export GrassmannBundle, RelativeGrassmannianBundle, grassmannized_bundle
export relative_tangent_bundle, relative_cotangent_bundle

"""
    GrassmannBundle(k, E)

The bundle of `k`-dimensional subspaces of `E` over a partial flag variety.
Requires `0 < k ≤ rank(E)`. The bundle `E` may be completely reducible or
filtered. Universal bundles have the convention `0 → S → π*E → Q → 0`.
`GrassmannBundle(1, E)` is the projective bundle of lines in `E`.
When `k == rank(E)`, the projection is the identity on the base.
"""
struct GrassmannBundle
  k::Int
  bundle::AmbientBundle
  # Fl(k,n;n+1) retains the GL(n) determinant character, lost on SL(n)/P_k.
  # This is representation bookkeeping, not the geometric ambient variety.
  auxiliary::PartialFlagVariety

  function GrassmannBundle(k::Integer, E::AmbientBundle)
    n = Int(rank(E))
    0 < k <= n || throw(ArgumentError("Require 0 < k ≤ rank(E)."))
    A = product(variety(E), flag_variety(n + 1, unique([Int(k), n])))
    new(Int(k), E, A)
  end
end

base_variety(G::GrassmannBundle) = variety(G.bundle)
grassmannized_bundle(G::GrassmannBundle) = G.bundle
dimension(G::GrassmannBundle) =
  dimension(base_variety(G)) + G.k * (Int(rank(G.bundle)) - G.k)
picard_rank(G::GrassmannBundle) = picard_rank(base_variety(G)) + (G.k < rank(G.bundle))
Base.:(==)(G::GrassmannBundle, H::GrassmannBundle) = G.k == H.k && G.bundle == H.bundle
Base.isequal(G::GrassmannBundle, H::GrassmannBundle) = G == H
Base.hash(G::GrassmannBundle, h::UInt) = hash(G.k, hash(G.bundle, h))
Base.show(io::IO, G::GrassmannBundle) = print(io, "Gr(", G.k, ", ", G.bundle, ")")

"""
    RelativeGrassmannianBundle

A direct sum of relative Levi bundles, generated by `S`, `Q`, their duals,
Schur functors and pullbacks from the base. Each irreducible fibre summand
has at most one higher direct image, so its Leray sequence degenerates.
The universal extension `π*E` is represented by `pullback(G, E)`, not `S ⊕ Q`.
"""
struct RelativeGrassmannianBundle <: Bundle
  variety::GrassmannBundle
  representation::AmbientBundle

  function RelativeGrassmannianBundle(G::GrassmannBundle, F::AmbientBundle)
    variety(F) == G.auxiliary ||
      throw(ArgumentError("Incorrect auxiliary representation space."))
    new(G, F)
  end
end

variety(F::RelativeGrassmannianBundle) = F.variety
rank(F::RelativeGrassmannianBundle) = rank(F.representation)
Base.iszero(F::RelativeGrassmannianBundle) = iszero(F.representation)
Base.:(==)(F::RelativeGrassmannianBundle, H::RelativeGrassmannianBundle) =
  F.variety == H.variety && F.representation == H.representation
Base.isequal(F::RelativeGrassmannianBundle, H::RelativeGrassmannianBundle) = F == H
Base.hash(F::RelativeGrassmannianBundle, h::UInt) =
  hash(F.representation, hash(F.variety, h))
Base.show(io::IO, F::RelativeGrassmannianBundle) =
  print(io, "Bundle(rank ", rank(F), " on ", variety(F), ")")

function pullback(G::GrassmannBundle, E::AmbientBundle)
  variety(E) == base_variety(G) || throw(ArgumentError("The bundle must live on the base."))
  RelativeGrassmannianBundle(G, _lift_bundle_to_product(G.auxiliary, E, 0))
end

function _grassmann_fibre_bundle(G::GrassmannBundle, i::Int)
  n = Int(rank(G.bundle))
  A = flag_variety(n + 1, unique([G.k, n]))
  offset = rank(dynkin_type(base_variety(G)))
  RelativeGrassmannianBundle(
    G, _lift_bundle_to_product(G.auxiliary, tautological_bundles(A)[i], offset)
  )
end

universal_subbundle(G::GrassmannBundle) = _grassmann_fibre_bundle(G, 1)
universal_quotient_bundle(G::GrassmannBundle) =
  G.k == rank(G.bundle) ? zero_bundle(G) : _grassmann_fibre_bundle(G, 2)
structure_sheaf(G::GrassmannBundle) = pullback(G, structure_sheaf(base_variety(G)))
zero_bundle(G::GrassmannBundle) = RelativeGrassmannianBundle(G, zero_bundle(G.auxiliary))
relative_line_bundle(G::GrassmannBundle, t::Integer=1) =
  RelativeGrassmannianBundle(
    G, _line_power(det(dual(universal_subbundle(G))).representation, t)
  )
O(G::GrassmannBundle, t::Integer=0) = relative_line_bundle(G, t)

function _grassmann_binary(op, E::RelativeGrassmannianBundle, F::RelativeGrassmannianBundle)
  variety(E) == variety(F) ||
    throw(ArgumentError("Bundles must live on the same Grassmann bundle."))
  RelativeGrassmannianBundle(variety(E), op(E.representation, F.representation))
end

tensor_product(E::AmbientBundle, F::RelativeGrassmannianBundle) =
  tensor_product(pullback(variety(F), E), F)
tensor_product(E::RelativeGrassmannianBundle, F::AmbientBundle) =
  tensor_product(E, pullback(variety(E), F))
_relative_pieces(F::CompletelyReducibleBundle) = [F]
_relative_pieces(F::FilteredBundle) = graded_pieces(F)
_relative_total(F::CompletelyReducibleBundle) = F
_relative_total(F::FilteredBundle) = total_bundle(F)

function _relative_direct_sum(E::AmbientBundle, F::AmbientBundle)
  iszero(E) && return F
  iszero(F) && return E
  E isa CompletelyReducibleBundle && F isa CompletelyReducibleBundle &&
    return direct_sum(E, F)
  # A direct sum admits the concatenation filtration; no extension is split.
  FilteredBundle(variety(E), vcat(_relative_pieces(E), _relative_pieces(F)))
end
direct_sum(E::RelativeGrassmannianBundle, F::RelativeGrassmannianBundle) =
  _grassmann_binary(_relative_direct_sum, E, F)
tensor_product(E::RelativeGrassmannianBundle, F::RelativeGrassmannianBundle) =
  _grassmann_binary(tensor_product, E, F)
Base.:+(E::RelativeGrassmannianBundle, F::RelativeGrassmannianBundle) = direct_sum(E, F)
Base.:*(E::RelativeGrassmannianBundle, F::RelativeGrassmannianBundle) = tensor_product(E, F)
function Base.:*(n::Integer, E::RelativeGrassmannianBundle)
  n >= 0 || throw(ArgumentError("Multiplicity must be nonnegative."))
  reduce(direct_sum, Iterators.repeated(E, n); init=zero_bundle(variety(E)))
end
dual(E::RelativeGrassmannianBundle) =
  RelativeGrassmannianBundle(variety(E), dual(E.representation))
exterior_power(E::RelativeGrassmannianBundle, k::Integer) =
  RelativeGrassmannianBundle(variety(E), exterior_power(E.representation, k))
symmetric_power(E::RelativeGrassmannianBundle, k::Integer) =
  RelativeGrassmannianBundle(variety(E), symmetric_power(E.representation, k))
schur_functor(E::RelativeGrassmannianBundle, λ::AbstractVector{<:Integer}) =
  RelativeGrassmannianBundle(variety(E), schur_functor(E.representation, λ))
det(E::RelativeGrassmannianBundle) =
  RelativeGrassmannianBundle(variety(E), det(E.representation))
determinant(E::RelativeGrassmannianBundle) = det(E)
twist(E::RelativeGrassmannianBundle, t::Integer) = tensor_product(E, O(variety(E), t))

relative_tangent_bundle(G::GrassmannBundle) =
  tensor_product(dual(universal_subbundle(G)), universal_quotient_bundle(G))
relative_cotangent_bundle(G::GrassmannBundle) = dual(relative_tangent_bundle(G))
canonical_bundle(G::GrassmannBundle) = tensor_product(
  O(G, -Int(rank(G.bundle))),
  pullback(
    G, tensor_product(canonical_bundle(base_variety(G)), _line_power(det(G.bundle), -G.k))
  ),
)
anticanonical_bundle(G::GrassmannBundle) = dual(canonical_bundle(G))

function cotangent_bundle(G::GrassmannBundle)
  horizontal = pullback(G, filtered_cotangent_bundle(base_variety(G)))
  vertical = relative_cotangent_bundle(G)
  RelativeGrassmannianBundle(
    G,
    FilteredBundle(
      G.auxiliary,
      vcat(_relative_pieces(horizontal.representation), [vertical.representation]),
    ),
  )
end
tangent_bundle(G::GrassmannBundle) = dual(cotangent_bundle(G))

"""
    pushforward(G::GrassmannBundle, F::RelativeGrassmannianBundle)

Higher direct images along `G → base_variety(G)`, by relative Borel--Weil--Bott.
Full GL weights are evaluated as Schur functors of `grassmannized_bundle(G)∨`.
Determinant characters are retained, including for negative weights.
"""
function pushforward(G::GrassmannBundle, F::RelativeGrassmannianBundle)
  variety(F) == G || throw(ArgumentError("The bundle must live on G."))
  F.representation isa CompletelyReducibleBundle || throw(
    ArgumentError(
      "Pushforward of an extension requires its differentials; use cohomology or Euler characteristics."
    ),
  )
  X = base_variety(G)
  n = Int(rank(G.bundle))
  b = rank(dynkin_type(X))
  d = G.k * (n - G.k)
  entries = AmbientBundle[zero_bundle(X) for _ in 0:d]
  schurs = Dict{Vector{Int},AmbientBundle}()
  for (rep, multiplicity) in _to_counts(F.representation)
    c = collect(coefficients(p_dominant_weight(rep)))
    fibre_weight = WeightLatticeElem(TypeA{n}, c[(b + 1):end])
    result = borel_weil_bott(fibre_weight, 1:(n - 1))
    result === nothing && continue
    q, μ = result
    a = collect(coefficients(μ))
    λ = reverse(cumsum(reverse(a)))
    image = get!(schurs, λ) do
      schur_functor(dual(G.bundle), λ)
    end
    base_factor = CompletelyReducibleBundle(X, c[1:b])
    scaled = tensor_product(multiplicity * base_factor, image)
    entries[q + 1] = _relative_direct_sum(entries[q + 1], scaled)
  end
  if all(A -> A isa CompletelyReducibleBundle, entries)
    return Cohomology{CompletelyReducibleBundle}(CompletelyReducibleBundle[entries...], d)
  end
  Cohomology{AmbientBundle}(entries, d)
end

"""Cohomology of a direct sum of relative Levi bundles by fibrewise BWB and Leray."""
function cohomology(F::RelativeGrassmannianBundle)
  entries = _relative_filtered_cohomology(F, Ref(0))
  d = dimension(variety(F))
  if F.representation isa CompletelyReducibleBundle &&
    variety(F).bundle isa CompletelyReducibleBundle
    return Cohomology{BigInt}([e.constant for e in entries], d)
  end
  _renumber_variables!(entries)
  Cohomology{AffineExpr}(entries, d)
end

function euler_characteristic(F::RelativeGrassmannianBundle)
  R = _relative_total(F.representation)
  images = pushforward(variety(F), RelativeGrassmannianBundle(variety(F), R))
  sum(
    (
      (-1)^q * euler_characteristic(_relative_total(images[q])) for q in 0:lastindex(images)
    );
    init=BigInt(0),
  )
end
chi(F::RelativeGrassmannianBundle) = euler_characteristic(F)

# A differential in the filtration spectral sequence goes from a quotient
# layer to an earlier subbundle layer and increases total cohomological degree.
function _relative_filtered_cohomology(F::RelativeGrassmannianBundle, counter::Ref{Int})
  F.representation isa CompletelyReducibleBundle &&
    return _relative_levi_cohomology(F, counter)
  G = variety(F)
  pieces = _relative_pieces(F.representation)
  rows = [
    _relative_levi_cohomology(RelativeGrassmannianBundle(G, p), counter) for p in pieces
  ]
  entries = [
    sum((row[q + 1] for row in rows); init=AffineExpr(0)) for q in 0:dimension(G)
  ]
  for q in 0:(dimension(G) - 1)
    possible = any(
      !is_zero_expr(rows[j][q + 1]) && !is_zero_expr(rows[i][q + 2]) for
      j in eachindex(rows) for i in 1:(j - 1)
    )
    possible || continue
    cancellation = _fresh_variable(counter)
    entries[q + 1] -= cancellation
    entries[q + 2] -= cancellation
  end
  entries
end

function _relative_levi_cohomology(F::RelativeGrassmannianBundle, counter::Ref{Int})
  G = variety(F)
  images = pushforward(G, F)
  entries = [AffineExpr(0) for _ in 0:dimension(G)]
  for q in 0:lastindex(images)
    A = images[q]
    row = if A isa FilteredBundle
      _cohomology_filtered(A, counter)
    else
      AffineExpr.(cohomology(A).entries)
    end
    for p in 0:dimension(base_variety(G))
      entries[p + q + 1] += row[p + 1]
    end
  end
  entries
end
